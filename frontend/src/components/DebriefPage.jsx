import React, { useCallback, useEffect, useMemo, useState } from "react";
import { Copy, Download, Printer, MessageSquarePlus, ArrowRight } from "lucide-react";
import { api, formatErrorMessage } from "../api";
import { Button, Skeleton, Slip } from "./ui";
import Readiness from "./Readiness";

const PRIORITY = {
  high: { label: "Ask first", dot: "bg-error" },
  medium: { label: "Ask next", dot: "bg-goldenrod" },
  low: { label: "If there is time", dot: "bg-outline" },
};

function fmtDate(iso) {
  if (!iso) return "";
  const d = new Date(iso + "T00:00:00");
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

function toMarkdown(data) {
  const p = data.project || {};
  const lines = [`# Debrief questions for ${p.leaver_name} (${p.name})`, "", `Leaving: ${fmtDate(p.departure_date)}`, ""];
  ["high", "medium", "low"].forEach((k) => {
    const qs = data.questions.filter((q) => q.priority === k && !q.answered);
    if (!qs.length) return;
    lines.push(`## ${PRIORITY[k].label}`, "");
    qs.forEach((q, i) => {
      lines.push(`${i + 1}. ${q.question}`, `   - Why: ${q.reason} (claim #${q.claim_id}, ${q.topic})`);
      if (q.quote) lines.push(`   - Record says: "${q.quote}"`);
      lines.push("");
    });
  });
  lines.push("Generated by Backstop from the checked claims, with plain rules and no AI.");
  return lines.join("\n");
}

function Question({ q, n, onAnswered, setActiveTab }) {
  const [open, setOpen] = useState(false);
  const [text, setText] = useState("");
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState(null);
  const [saved, setSaved] = useState(null);

  const save = async () => {
    if (busy) return;
    const t = text.trim();
    if (!t) {
      setErr("Type what they said before saving.");
      return;
    }
    setBusy(true);
    setErr(null);
    try {
      const res = await api.answerDebrief({ questionClaimId: q.claim_id, answer: t });
      setSaved(res.answer_claim);
      setOpen(false);
      onAnswered?.();
    } catch (e) {
      setErr(formatErrorMessage(e));
    } finally {
      setBusy(false);
    }
  };

  const answerId = saved?.id || q.answer_claim_id;
  return (
    <li className="grid grid-cols-[2.25rem_1fr] gap-x-3 py-5 border-t border-outline-variant first:border-t-0">
      <span className="font-mono tnum text-[13px] text-outline pt-0.5">{n}.</span>
      <div className="flex flex-col gap-2 min-w-0">
        <p className={`text-[16px] leading-6 font-semibold text-balance ${q.answered || saved ? "text-on-surface-variant" : "text-on-surface"}`}>{q.question}</p>
        <p className="text-[13px] text-on-surface-variant flex flex-wrap items-center gap-x-2 gap-y-1">
          <span>{q.reason}</span>
          <span aria-hidden="true">·</span>
          <span className="font-mono">{q.topic}</span>
          <span aria-hidden="true">·</span>
          <a
            href={`#/review/${q.claim_id}`}
            onClick={(e) => {
              e.preventDefault();
              setActiveTab("review", q.claim_id);
            }}
            className="font-mono text-primary underline decoration-primary/30 hover:decoration-primary"
          >
            claim #{q.claim_id}
          </a>
        </p>
        {q.quote && (
          <p className="font-mono text-[13px] leading-5 text-on-surface-variant border-l border-outline-variant pl-3 line-clamp-3">
            {q.quote}
          </p>
        )}

        {answerId ? (
          <Slip
            className="self-start mt-1"
            who="Lead"
            when="answer recorded"
            what={
              <a
                href={`#/review/${answerId}`}
                onClick={(e) => {
                  e.preventDefault();
                  setActiveTab("review", answerId);
                }}
                className="underline decoration-stamp/40 hover:decoration-stamp"
              >
                Saved as claim #{answerId}, waiting to be checked
              </a>
            }
          />
        ) : open ? (
          <div className="flex flex-col gap-2 mt-1 max-w-[68ch] no-print">
            <label htmlFor={`ans-${q.claim_id}`} className="text-[13px] font-semibold">
              What did they say?
            </label>
            <textarea
              id={`ans-${q.claim_id}`}
              value={text}
              maxLength={2000}
              onChange={(e) => setText(e.target.value)}
              className="w-full min-h-24 p-3 rounded-[6px] border border-outline-variant bg-surface-container-lowest text-[14px] leading-[22px] focus:border-stamp"
              placeholder="Their words, as close to verbatim as you can. This becomes the quote."
            />
            {err && <p role="alert" className="text-[13px] text-error">{err}</p>}
            <div className="flex items-center gap-2">
              <Button variant="stamp" size="sm" onClick={save} disabled={busy}>
                {busy ? "Saving…" : "Save answer"}
              </Button>
              <Button variant="ghost" size="sm" onClick={() => setOpen(false)} disabled={busy}>
                Cancel
              </Button>
              <span className="text-[12px] text-on-surface-variant">It is added as a new claim you still have to approve.</span>
            </div>
          </div>
        ) : (
          <button
            type="button"
            onClick={() => setOpen(true)}
            className="no-print self-start mt-1 inline-flex items-center gap-1.5 min-h-9 -ml-1 px-1 text-[13px] font-semibold text-stamp hover:underline cursor-pointer"
          >
            <MessageSquarePlus size={15} aria-hidden="true" />
            Record their answer
          </button>
        )}
      </div>
    </li>
  );
}

export default function DebriefPage({ setActiveTab, onChanged }) {
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);
  const [filter, setFilter] = useState("open");
  const [copied, setCopied] = useState(false);

  const load = useCallback(async () => {
    setError(null);
    try {
      setData(await api.getDebrief({ role: "lead" }));
    } catch (e) {
      setError(formatErrorMessage(e));
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const questions = useMemo(() => data?.questions || [], [data]);
  const shown = useMemo(
    () => questions.filter((q) => (filter === "all" ? true : filter === "open" ? !q.answered : q.answered)),
    [questions, filter]
  );
  const openCount = questions.filter((q) => !q.answered).length;

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(toMarkdown(data));
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      setError("Copy was blocked by the browser. Use Download instead.");
    }
  };
  const download = () => {
    const blob = new Blob([toMarkdown(data)], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "debrief-questions.md";
    a.click();
    URL.revokeObjectURL(url);
  };

  if (error && !data) {
    return (
      <div role="alert" className="flex flex-col items-start gap-3 py-10">
        <h1 className="text-[24px] font-bold">The debrief questions did not load</h1>
        <p className="text-[14px] text-on-surface-variant">{error}</p>
        <Button onClick={load}>Try again</Button>
      </div>
    );
  }

  const p = data?.project;
  return (
    <div className="flex flex-col gap-10 pb-10">
      <header className="flex flex-col gap-3 max-w-[72ch]">
        <h1 className="text-[30px] sm:text-[36px] leading-[1.1] font-bold tracking-[-0.02em]">Debrief questions</h1>
        {p ? (
          <p className="text-[16px] leading-7 text-on-surface-variant">
            What the records could not settle, as questions to ask <strong className="text-on-surface font-semibold">{p.leaver_name}</strong> before{" "}
            {fmtDate(p.departure_date)}. Record each answer while they are still here: it becomes a claim with its own quote, checked like any other.
          </p>
        ) : (
          <Skeleton className="h-14 w-full" />
        )}
      </header>

      {data ? <Readiness readiness={data.readiness} /> : <Skeleton className="h-24 w-full" />}

      <section aria-labelledby="q-h" className="flex flex-col gap-4">
        <div className="flex flex-wrap items-center justify-between gap-3 no-print">
          <div className="flex items-baseline gap-3">
            <h2 id="q-h" className="text-[20px] font-bold">
              Questions
            </h2>
            {data && (
              <span className="text-[13px] text-on-surface-variant">
                <span className="font-mono tnum">{openCount}</span> open of <span className="font-mono tnum">{questions.length}</span>
              </span>
            )}
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <div role="group" aria-label="Show" className="inline-flex p-0.5 rounded-[7px] bg-surface-container">
              {[
                ["open", "Open"],
                ["answered", "Answered"],
                ["all", "All"],
              ].map(([k, l]) => (
                <button
                  key={k}
                  type="button"
                  aria-pressed={filter === k}
                  onClick={() => setFilter(k)}
                  className={`h-8 px-3 rounded-[6px] text-[13px] font-semibold cursor-pointer ${
                    filter === k ? "bg-surface-container-lowest text-on-surface ring-1 ring-outline-variant" : "text-on-surface-variant hover:text-on-surface"
                  }`}
                >
                  {l}
                </button>
              ))}
            </div>
            <Button size="sm" onClick={copy} disabled={!data}>
              <Copy size={14} aria-hidden="true" /> {copied ? "Copied" : "Copy"}
            </Button>
            <Button size="sm" onClick={download} disabled={!data}>
              <Download size={14} aria-hidden="true" /> Download
            </Button>
            <Button size="sm" onClick={() => window.print()} disabled={!data}>
              <Printer size={14} aria-hidden="true" /> Print
            </Button>
          </div>
        </div>

        {error && data && <p role="alert" className="text-[13px] text-error">{error}</p>}

        {!data ? (
          <div className="flex flex-col gap-3">
            <Skeleton className="h-16 w-full" />
            <Skeleton className="h-16 w-full" />
          </div>
        ) : (data.questions || []).length === 0 && !(data.readiness?.parts || []).some((p) => p.total > 0 && p.key !== "signed") ? (
          <div className="py-10 flex flex-col items-start gap-3 border-t border-outline-variant">
            <p className="text-[15px] font-semibold">No claims yet, so there is nothing to ask.</p>
            <p className="text-[14px] text-on-surface-variant max-w-[60ch]">
              Add records and build claims. Gaps, disagreements and modules only one person knows turn into questions here.
            </p>
            <Button variant="primary" size="sm" onClick={() => setActiveTab("records")}>
              Add records <ArrowRight size={14} aria-hidden="true" />
            </Button>
          </div>
        ) : shown.length === 0 ? (
          <div className="py-10 flex flex-col items-start gap-3 border-t border-outline-variant">
            <p className="text-[15px] font-semibold">
              {filter === "answered" ? "No answers recorded yet." : "No open questions. Every gap has an answer or a decision."}
            </p>
            <p className="text-[14px] text-on-surface-variant max-w-[60ch]">
              {filter === "answered"
                ? "Open a question and record what the person leaving said. The answer is checked like any other claim."
                : "Check the new answers on the review queue, then the handover is ready to sign."}
            </p>
            <Button variant="primary" size="sm" onClick={() => (filter === "answered" ? setFilter("open") : setActiveTab("review"))}>
              {filter === "answered" ? "Show open questions" : "Check the claims"} <ArrowRight size={14} aria-hidden="true" />
            </Button>
          </div>
        ) : (
          ["high", "medium", "low"].map((k) => {
            const qs = shown.filter((q) => q.priority === k);
            const offset = ["high", "medium", "low"].slice(0, ["high", "medium", "low"].indexOf(k)).reduce((acc, kk) => acc + shown.filter((q) => q.priority === kk).length, 0);
            if (!qs.length) return null;
            return (
              <section key={k} aria-labelledby={`pri-${k}`} className="flex flex-col">
                <h3 id={`pri-${k}`} className="flex items-center gap-2 text-[14px] font-semibold text-on-surface-variant pb-1">
                  <span aria-hidden="true" className={`w-2 h-2 rounded-full ${PRIORITY[k].dot}`} />
                  {PRIORITY[k].label}
                  <span className="font-mono tnum text-outline">{qs.length}</span>
                </h3>
                <ol>
                  {qs.map((q, i) => (
                    <Question key={q.claim_id} q={q} n={offset + i + 1} setActiveTab={setActiveTab} onAnswered={() => { load(); onChanged?.(); }} />
                  ))}
                </ol>
              </section>
            );
          })
        )}

        {data?.withheld_count > 0 && (
          <p className="text-[13px] text-on-surface-variant border-t border-outline-variant pt-3">
            {data.withheld_count === 1 ? "1 more question comes" : `${data.withheld_count} more questions come`} from notes above the lead's access. They are counted here and never shown.
          </p>
        )}
        <p className="text-[12.5px] text-outline">{data?.note}</p>
      </section>
    </div>
  );
}
